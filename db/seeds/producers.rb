  puts "- Seeding producer: #{attrs[:name]}"
  if attrs[:country_id] != current_country_id_name
    current_country_id_name = attrs[:country_id]
    country = Country.find_by(name: attrs[:country_id])
  end
  attrs[:country_id] = country.id
  puts "  - attrs: #{attrs.inspect}"

  grapes = attrs.delete(:grapes)
  regions = attrs.delete(:regions)
  logo_url = attrs.delete(:logo_url)
