  puts "  - Regions: #{regions.inspect}"
  puts "  - Logo URL: #{logo_url}"
  puts "  - attrs: #{attrs.inspect}"
  producer = Producer.find_or_initialize_by(name: attrs[:name])
  producer.assign_attributes(attrs)
  producer.save!

  # Associated Grape lookup and linkage
  if grapes
    puts "  - Linking grapes and regions for producer: #{attrs[:grapes]}"
    grapes.each do |grape_name|
      grape = Grape.where(name: grape_name).first
      producer.grapes << grape if grape && !producer.grapes.include?(grape)
    end
  end
  if regions
    puts "  - Linking regions for producer: #{attrs[:regions]}"
    regions.each do |region_name|
      region = Region.where(name: region_name).first
      producer.regions << region if region && !producer.regions.include?(region)
    end
  end

  puts "- Seeded producer: #{producer.name}"
end

